def bundled_label(iri: str) -> str | None:
    label = BUNDLED.get(iri)
    if label is None and iri.startswith("https://") and "creativecommons.org" in iri:
        label = BUNDLED.get("http://" + iri.removeprefix("https://"))
    return label
